/* ---- record ---- */
fs.mkdirSync(DIR, { recursive: true });
const jobs = [...texts].map(text => ({
  text,
  file: crypto.createHash('sha1').update(text).digest('hex').slice(0, 12) + '.mp3'
}));

function record(job, attempt) {
  return new Promise((resolve, reject) => {
    const out = path.join(DIR, job.file);
    if (fs.existsSync(out) && fs.statSync(out).size > 4000) return resolve('cached');
    execFile('edge-tts',
      ['--voice', VOICE, '--rate=' + RATE, '--text', job.text, '--write-media', out],
      { timeout: 60000 },
      (err) => {
        if (!err && fs.existsSync(out) && fs.statSync(out).size > 4000) return resolve('made');
        if ((attempt || 0) < 2) return resolve(record(job, (attempt || 0) + 1));
        reject(new Error('failed: ' + job.text.slice(0, 50)));
      });
  });
}

(async () => {
  let done = 0, made = 0;
  const pool = 8;
  const queue = [...jobs];
  await Promise.all(Array.from({ length: pool }, async () => {
    while (queue.length) {
      const job = queue.shift();
      const r = await record(job);
      if (r === 'made') made++;
      if (++done % 25 === 0) console.log(done + '/' + jobs.length);
    }
  }));
  const map = {};
  jobs.sort((a, b) => a.text < b.text ? -1 : 1)
      .forEach(j => { map[j.text] = 'voice/' + j.file; });
  fs.writeFileSync(path.join(__dirname, 'voicepack.js'),
    '// Generated by make-voicepack.js — voice: ' + VOICE + ', rate ' + RATE + '\n' +
    'window.VOICE_PACK = ' + JSON.stringify(map, null, 1) + ';\n');
  // prune clips no line uses any more
  const used = new Set(jobs.map(j => j.file));
  let pruned = 0;
  for (const f of fs.readdirSync(DIR)) {
    if (!used.has(f)) { fs.unlinkSync(path.join(DIR, f)); pruned++; }
  }
  if (pruned) console.log('pruned ' + pruned + ' stale clips');
  const bytes = jobs.reduce((s, j) => s + fs.statSync(path.join(DIR, j.file)).size, 0);
  console.log('clips: ' + jobs.length + ' (' + made + ' new), total ' + Math.round(bytes / 1024) + ' KB');
})();
