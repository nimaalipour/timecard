/*
  Records every line the game can speak with a neural voice (edge-tts,
  en-US-AvaNeural) into voice/<hash>.mp3, and writes voicepack.js — a map
  from the exact spoken text to its clip. The game plays these clips and
  only falls back to the device's built-in voice when a clip is missing.

      node make-voicepack.js

  Requires: pip install edge-tts  (and network access while generating).
  Re-run after changing any text in content.js — new lines get new clips,
  unchanged lines are skipped.

  Lines with {name} are recorded with the default pilot's name; if a
  different name is typed on the start screen, just those lines fall back
  to the device voice.
*/
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFile } = require('child_process');

const VOICE = 'en-US-AvaNeural';
const RATE = '-10%';
const DIR = path.join(__dirname, 'voice');

/* ---- load the game's content ---- */
global.window = {};
require('./content.js');
const C = global.window.TSR_CONTENT;
const fmt = (s) => s.replace(/\{name\}/g, C.defaultPilot);

/* ---- every string the game can say ---- */
const texts = new Set();
C.howLines.forEach((t) => texts.add(fmt(t)));
C.praises.forEach((t) => texts.add(fmt(t)));
C.misses.forEach((t) => texts.add(t));
texts.add(fmt(C.lastLife));
let maxChoices = 0;
for (const q of C.questions) {
  texts.add(q.story);
  texts.add(q.q);
  q.choices.forEach((c) => texts.add(c.t));    // answers shuffle, so the
  maxChoices = Math.max(maxChoices, q.choices.length);   // numbers are separate clips
  const right = q.choices.find((c) => c.ok);
  texts.add('The right answer was: ' + right.t + '.');
  texts.add(q.f);
}
for (let n = 1; n <= maxChoices; n++) texts.add('Number ' + n + '.');
for (const tier of Object.values(C.wins)) {
  texts.add(fmt(tier.title));
  texts.add(fmt(tier.msg));
}
texts.add(fmt(C.lose.title));
texts.add(fmt(C.lose.msg));

